const POR_MUNICIPIO = new Map<string, RegiaoMunicipio>(
  DADOS.map(([chave, [imediata, microrregiao, intermediaria]]) => [
    chave,
    { imediata, microrregiao, intermediaria },
  ]),
);

export function regiaoDe(chaveMunicipio: string | null | undefined): RegiaoMunicipio | null {
  if (!chaveMunicipio) return null;
  return POR_MUNICIPIO.get(chaveMunicipio) ?? null;
}

/**
 * Municípios da mesma região imediata (a vizinhança do IBGE). Quando a região
 * tem poucos integrantes, completa com a microrregião, para o comparativo
 * nunca ficar com dois ou três nomes só.
 */
export function vizinhosDe(chaveMunicipio: string | null | undefined, minimo = 6): string[] {
  const base = regiaoDe(chaveMunicipio);
  if (!base) return [];
  const imediata = DADOS.filter(([, r]) => r[0] === base.imediata).map(([c]) => c);
  if (imediata.length >= minimo) return imediata;
  const micro = DADOS.filter(([, r]) => r[1] === base.microrregiao).map(([c]) => c);
  return [...new Set([...imediata, ...micro])];
}
